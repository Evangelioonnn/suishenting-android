package com.museum.reader.recording

import android.content.Context
import android.media.MediaRecorder
import android.media.AudioManager
import android.media.AudioFocusRequest
import android.media.AudioAttributes
import android.os.Handler
import android.os.Looper
import android.os.Build
import com.museum.reader.data.AudioFiles
import com.museum.reader.data.DocumentRepository
import com.museum.reader.model.AudioKind
import com.museum.reader.model.SentenceAudio
import java.io.File
import java.util.UUID
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONObject

data class PendingRecording(
    val id: String, val documentId: String, val sentenceId: String,
    val textHash: String, val path: String, val durationMs: Long,
    val playable: Boolean,
)

/** Raw capture is immutable. A re-recording becomes current only after explicit confirmation. */
class SentenceRecordingManager(private val context: Context, private val repository: DocumentRepository) {
    private var recorder: MediaRecorder? = null
    private var active: PendingRecording? = null
    var onInterrupted: (() -> Unit)? = null
    private var focus: AudioFocusRequest? = null
    private val audioManager = context.getSystemService(AudioManager::class.java)
    private val main = Handler(Looper.getMainLooper())
    private val journals get() = File(context.filesDir, "recording-pending").apply { mkdirs() }

    fun start(documentId: String, sentenceId: String, text: String) {
        check(recorder == null && active == null) { "已有录音正在进行" }
        val id = UUID.randomUUID().toString()
        val hash = DocumentRepository.textHash(text)
        val directory = AudioFiles.requireOwned(context, File(context.filesDir, "sentence-audio/recordings/$documentId"))
            .apply { check(isDirectory || mkdirs()) { "无法创建录音目录，请检查存储空间" } }
        val file = File(directory, "$sentenceId-recording-${hash.take(12)}-$id.m4a")
        val pending = PendingRecording(id, documentId, sentenceId, hash, file.path, 0, false)
        writeJournal(pending)
        val engine = createRecorder()
        try {
            val request = AudioFocusRequest.Builder(AudioManager.AUDIOFOCUS_GAIN_TRANSIENT_EXCLUSIVE)
                .setAudioAttributes(AudioAttributes.Builder().setUsage(AudioAttributes.USAGE_MEDIA)
                    .setContentType(AudioAttributes.CONTENT_TYPE_SPEECH).build())
                .setWillPauseWhenDucked(true)
                .setOnAudioFocusChangeListener({ change ->
                    if (change < AudioManager.AUDIOFOCUS_GAIN && active?.id == id) onInterrupted?.invoke()
                }, main).build()
            check(audioManager.requestAudioFocus(request) == AudioManager.AUDIOFOCUS_REQUEST_GRANTED) {
                "音频正在被其他应用使用"
            }
            focus = request
            engine.setOnErrorListener { _, _, _ -> main.post { if (active?.id == id) onInterrupted?.invoke() } }
            engine.setAudioSource(MediaRecorder.AudioSource.VOICE_RECOGNITION)
            engine.setOutputFormat(MediaRecorder.OutputFormat.MPEG_4)
            engine.setAudioEncoder(MediaRecorder.AudioEncoder.AAC)
            engine.setAudioSamplingRate(44_100)
            engine.setAudioEncodingBitRate(96_000)
            engine.setOutputFile(file.path)
            engine.prepare()
            engine.start()
            recorder = engine
            active = pending
        } catch (error: Exception) {
            runCatching { engine.release() }
            releaseFocus()
            if (!file.exists() || file.length() == 0L) {
                file.delete()
                journal(id).delete()
            }
            // Preserve any generated bytes; startup recovery can inspect them.
            throw IllegalStateException("无法开始录音，请检查麦克风权限和手机存储空间", error)
        }
    }

    fun maxAmplitude(): Int = runCatching { recorder?.maxAmplitude ?: 0 }.getOrDefault(0)

    suspend fun endCapture(): PendingRecording? {
        val pending = stopCapture() ?: return null
        return withContext(Dispatchers.IO) { inspect(pending).also {
            writeJournal(it)
            if (it.playable) archivePending(it)
        } }
    }

    /** Process teardown still leaves the raw file and journal, rather than silently deleting a take. */
    fun preserveImmediately() { stopCapture() }
    private fun stopCapture(): PendingRecording? {
        val engine = recorder ?: return null
        val pending = active ?: return null
        recorder = null; active = null
        runCatching { engine.stop() }
        runCatching { engine.release() }
        releaseFocus()
        return pending
    }

    suspend fun pendingRecordings(): List<PendingRecording> = withContext(Dispatchers.IO) {
        journals.listFiles().orEmpty().filter { it.isFile && it.extension == "json" }.mapNotNull { journal ->
            runCatching {
                require(journal.nameWithoutExtension.matches(Regex("[a-f0-9-]{36}")))
                val json = JSONObject(journal.readText())
                val path = AudioFiles.requireOwned(context, File(json.getString("path")))
                inspect(PendingRecording(journal.nameWithoutExtension, json.getString("documentId"),
                    json.getString("sentenceId"), json.getString("textHash"), path.path, 0, false))
            }.getOrNull()
        }
    }

    suspend fun save(pending: PendingRecording): SentenceAudio = withContext(Dispatchers.IO) {
        val verified = inspect(pending)
        require(verified.playable && verified.durationMs >= 300) {
            "这份录音过短或不可播放，原有效录音未被替换。可重新录制或保留待处理文件"
        }
        val audio = verified.toAudio(null)
        require(repository.putAudioIfCurrent(audio)) {
            "录音所属句子已修改或删除，未替换有效录音。原文件已保留，可在存储维护中处理"
        }
        check(journal(pending.id).delete() || !journal(pending.id).exists()) { "录音已保存，但待确认记录整理失败，请重新打开" }
        audio
    }

    suspend fun discard(pending: PendingRecording) = withContext(Dispatchers.IO) {
        val file = AudioFiles.requireOwned(context, File(pending.path))
        // If already confirmed before an interruption, never delete the active recording.
        val current = repository.allAudioAssets().firstOrNull { it.id == pending.id }
        require(current?.archivedAt != null || current == null) { "该录音已保存，不再属于待确认录音" }
        if (file.exists()) check(file.delete()) { "无法移除待确认录音，请停止试听后重试" }
        repository.deleteAudio(pending.id)
        check(journal(pending.id).delete() || !journal(pending.id).exists()) { "待确认记录整理失败，请重试" }
    }

    private suspend fun archivePending(pending: PendingRecording) {
        val current = repository.allAudioAssets().firstOrNull { it.id == pending.id }
        if (current == null) try { repository.putAudio(pending.toAudio(System.currentTimeMillis())) }
        catch (cancelled: kotlinx.coroutines.CancellationException) { throw cancelled }
        catch (_: Exception) { /* Raw file and its pending journal remain recoverable. */ }
    }
    private fun PendingRecording.toAudio(archivedAt: Long?) = SentenceAudio(id, documentId, sentenceId,
        AudioKind.RECORDING, "local", "self", path, textHash, durationMs, archivedAt)

    private fun inspect(pending: PendingRecording): PendingRecording {
        val file = AudioFiles.requireOwned(context, File(pending.path))
        val info = AudioFiles.inspect(file)
        return pending.copy(durationMs = info?.durationMs ?: 0, playable = info != null)
    }
    private fun journal(id: String): File {
        require(id.matches(Regex("[a-f0-9-]{36}"))) { "待确认录音编号不合法" }
        return File(journals, "$id.json")
    }
    private fun writeJournal(pending: PendingRecording) {
        AudioFiles.writeAtomic(journal(pending.id), JSONObject().put("documentId", pending.documentId)
            .put("sentenceId", pending.sentenceId).put("textHash", pending.textHash)
            .put("path", AudioFiles.requireOwned(context, File(pending.path)).path).toString())
    }
    private fun releaseFocus() {
        focus?.let(audioManager::abandonAudioFocusRequest)
        focus = null
    }
    @Suppress("DEPRECATION")
    private fun createRecorder(): MediaRecorder =
        if (Build.VERSION.SDK_INT >= 31) MediaRecorder(context) else MediaRecorder()
}
